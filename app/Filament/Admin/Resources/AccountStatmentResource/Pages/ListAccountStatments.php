<?php

namespace App\Filament\Admin\Resources\AccountStatmentResource\Pages;

use App\Filament\Admin\Resources\AccountStatmentResource;
use Filament\Actions;
use Filament\Resources\Components\Tab;
use Filament\Resources\Pages\ListRecords;
use Illuminate\Database\Eloquent\Builder;
use App\Filament\Admin\Resources\AccountStatmentResource\Widgets\AccountStats;
use Filament\Pages\Concerns\ExposesTableToWidgets;

use App\Enums\BalanceTypeEnum;
use App\Filament\Admin\Resources\AccountResource;
use App\Models\Balance;
use App\Models\User;


use Filament\Forms\Components\Select;
use Filament\Forms\Components\TextInput;
use Filament\Notifications\Notification;
use Illuminate\Support\Facades\DB;
use App\Enums\ActivateStatusEnum;
use Livewire\Attributes\Url;

class ListAccountStatments extends ListRecords
{
    use ExposesTableToWidgets;
    protected static string $resource = AccountStatmentResource::class;

    protected function getHeaderActions(): array
    {
        return [
            Actions\CreateAction::make(),
            Actions\Action::make('quid_pending')->form([
                Select::make('source_id')->options(User::WithAccount()->active()->select('id', 'name')->pluck('name', 'id'))->searchable()->label(' الحساب')->required(),

                TextInput::make('amount')
                ->default(function () {
                    return 0; // يمكنك استبدال هذا بحساب ديناميكي
                })
                ->disabled()->label('القيمة'),
                TextInput::make('info')->default('سند تعليق')->label('ملاحظات')
           ])
                ->action(function ($data) {
                    DB::beginTransaction();
                    try {
                        $uuid = \Str::uuid();
                        Balance::create([
                            'user_id' => $data['source_id'],
                            'currency_id' => 1,
                            'pending' => false,
                            'is_complete' => true,
                            'info' => $data['info'],
                            'uuid' => $uuid,
                            'type' => BalanceTypeEnum::PUSH->value,
                            'credit' => 0,
                            'debit' => 0,
                            'customer_name' => User::find($data['source_id'])?->name,
                        ]);

                        DB::commit();
                        Notification::make('error')->success()->title('نجاح العملية')->body('تم إضافة السند بنجاح')->send();
                    } catch (\Exception | \Error $e) {
                        DB::rollBack();
                        Notification::make('error')->danger()->title('خطأ في العملية')->body($e->getMessage())->send();
                    }
                })->label('سند تعليق'),
        ];
    }
    public function getTabs(): array
    {
        return [
            Tab::make('all')->modifyQueryUsing(fn($query)=>$query)->label('الكل'),
            Tab::make('usd')->modifyQueryUsing(fn($query)=>$query->where('currency_id',1))->label('USD'),
            Tab::make('try')->modifyQueryUsing(fn($query)=>$query->where('currency_id',2))->label('TRY'),
        ];
    }
    protected function getTableQuery(): ?Builder
    {
        return parent::getTableQuery()->where('is_complete',true)
            ->with(['order'=>fn($query)=>$query->with('sender','receive')])
            ->latest(); // TODO: Change the autogenerated stub
    }

    protected function getHeaderWidgets(): array
{

    return [
        AccountStats::class
    ];
}
}
